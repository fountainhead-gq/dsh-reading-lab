#!/usr/bin/env node
/**
 * 把 src/client/ 的片段拼成仓库根目录的 client.js（docs/05-dev.md §4，D-05-02）。
 *
 * 为什么不是打包器：DSH 浏览器端只有 `<script>` 与 `window.__ModuleLoader__`，
 * 模块工厂里的 `require` 只解析宿主模块表（react / react-dom），不解析相对路径，
 * 所以 Client 必须是单文件。拼接规则是确定性的：同样输入必得同样字节。
 *
 * 用法：
 *   node scripts/build-client.mjs           # 生成/覆盖 client.js
 *   node scripts/build-client.mjs --check   # 只比对，不一致退出 1（CI/verify 用）
 *   node scripts/build-client.mjs --stdout  # 打到 stdout（调试用）
 */
import { createHash } from 'node:crypto'
import { readFileSync, renameSync, writeFileSync, existsSync, rmSync } from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const TEMPLATE = path.join(ROOT, 'src', 'client', 'index.js')
const OUTPUT = path.join(ROOT, 'client.js')

/** 片段顺序固定：共享原语在前，视图在后（视图引用 store/api/t）。 */
export const PARTS = [
  'src/client/i18n.js',
  'src/client/styles.js',
  'src/client/store.js',
  'src/client/api.js',
  'src/client/views/header.js',
  'src/client/views/library.js',
  'src/client/views/canvas.js',
  'src/client/views/detail.js',
  'src/client/views/ask.js',
  'src/client/views/overlay.js',
]

const DICT_MARKER = '/* @build:dicts */'
const PARTS_MARKER = '/* @build:parts */'

function read(relative) {
  return readFileSync(path.join(ROOT, relative), 'utf8')
}

function loadDictionaries() {
  /** @type {Record<string, Record<string, string>>} */
  const dicts = {}
  for (const lang of ['zh', 'en']) {
    const raw = JSON.parse(read(`locale/${lang}.json`))
    /** @type {Record<string, string>} */
    const flat = {}
    for (const [key, value] of Object.entries(raw.ui ?? {})) flat[key] = value
    // errors.js 用 error.<CODE> 取文案，客户端保持同一套 key。
    for (const [code, value] of Object.entries(raw.error ?? {})) flat[`error.${code}`] = value
    dicts[lang] = flat
  }
  return dicts
}

function renderDictionaries(dicts) {
  return `const DICTS = ${JSON.stringify(dicts, null, 2)}`
}

function renderParts(parts) {
  return parts.map((relative) => {
    const body = read(relative).replace(/\s+$/, '')
    return `// ---- ${relative} ----\n${body}`
  }).join('\n\n')
}

function fingerprint(relativePaths) {
  const hash = createHash('sha256')
  for (const relative of relativePaths) {
    hash.update(relative)
    hash.update('\0')
    hash.update(read(relative))
    hash.update('\0')
  }
  return hash.digest('hex').slice(0, 16)
}

export function buildClient() {
  const template = read('src/client/index.js')
  for (const marker of [DICT_MARKER, PARTS_MARKER]) {
    const count = template.split(marker).length - 1
    if (count !== 1) {
      throw new Error(`src/client/index.js must contain exactly one ${marker} (found ${count})`)
    }
  }

  const dicts = loadDictionaries()
  const sources = ['src/client/index.js', ...PARTS, 'locale/zh.json', 'locale/en.json']
  const banner = [
    '// AUTO-GENERATED by scripts/build-client.mjs — do not edit.',
    `// sources: ${sources.length} files, fingerprint ${fingerprint(sources)}`,
    '// Regenerate with: npm run build:client',
  ].join('\n')

  return `${banner}\n${template
    .replace(DICT_MARKER, () => renderDictionaries(dicts))
    .replace(PARTS_MARKER, () => renderParts(PARTS))
    .replace(/\s+$/, '')}\n`
}

function main(argv) {
  const mode = argv.includes('--check') ? 'check' : argv.includes('--stdout') ? 'stdout' : 'write'
  const output = buildClient()

  if (mode === 'stdout') {
    process.stdout.write(output)
    return 0
  }

  if (mode === 'check') {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : null
    if (current === output) {
      process.stdout.write(`client.js is up to date (${Buffer.byteLength(output)} bytes)\n`)
      return 0
    }
    process.stderr.write('client.js is stale — run: npm run build:client\n')
    return 1
  }

  // 先写临时文件再改名：中途失败不会留下半个 client.js。
  const temporary = `${OUTPUT}.tmp`
  try {
    writeFileSync(temporary, output, 'utf8')
    // 语法自检（不 spawn 子进程，避免沙箱下的 stdio 限制）。
    try {
      new Function(output)
    } catch (error) {
      throw new Error(`generated client.js has a syntax error: ${error.message}`)
    }
    renameSync(temporary, OUTPUT)
  } catch (error) {
    if (existsSync(temporary)) rmSync(temporary, { force: true })
    throw error
  }
  process.stdout.write(`wrote client.js (${Buffer.byteLength(output)} bytes, ${PARTS.length} parts)\n`)
  return 0
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2))
}